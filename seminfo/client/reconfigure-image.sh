#!/bin/bash
# Reconfigure an existing SEMINFO ISO offline, preserving its hybrid boot setup.
# The source ISO and physical disks are never modified.
set -euo pipefail
[[ $# -eq 5 ]] || { echo 'Uso: reconfigure-image.sh INPUT.iso SHA256 OVERLAY OUTPUT.iso SENHA-MANUTENCAO.txt' >&2; exit 2; }
[[ $EUID -eq 0 ]] || { echo 'Execute no builder Linux como root' >&2; exit 1; }
source_iso=$(readlink -f "$1"); expected=$2; overlay=$(readlink -f "$3")
output=$(readlink -m "$4"); passfile=$(readlink -f "$5")
scripts=$(dirname "$(readlink -f "$0")")
[[ $expected =~ ^[0-9a-f]{64}$ ]] || { echo 'SHA256 da origem obrigatorio' >&2; exit 1; }
test -s "$source_iso"; test -d "$overlay"; test -s "$passfile"
test ! -e "$output"; test ! -e "$output.partial"
work=$(mktemp -d /work/seminfo-reconfigure.XXXXXX)
cleanup() {
    for point in dev/pts dev sys proc; do
        mountpoint -q "$work/root/$point" && umount -l "$work/root/$point" || true
    done
}
trap cleanup EXIT
echo 'Copiando e conferindo a ISO original no volume Linux...'
# Large reads avoid the per-read overhead of Windows bind mounts. All later
# ISO operations use this verified Linux-local copy, including boot replay.
python3 - "$source_iso" "$work/source.iso" "$expected" <<'PY'
import hashlib,sys
from pathlib import Path
source,target,expected=sys.argv[1:]
digest=hashlib.sha256();copied=0;reported=0;total=Path(source).stat().st_size
with open(source,'rb') as src,open(target,'xb') as dst:
    while data:=src.read(8*1024*1024):
        digest.update(data);dst.write(data);copied+=len(data)
        if copied-reported>=512*1024*1024:
            print(f'ISO original: {copied*100//total}% copiados/verificados',flush=True);reported=copied
if digest.hexdigest()!=expected:raise SystemExit('SHA256 da ISO original diverge')
print('SHA256 da origem aprovado.',flush=True)
PY
source_iso="$work/source.iso"
echo "Extraindo ISO para $work (origem preservada)..."
xorriso -osirrox on -indev "$source_iso" -extract / "$work/iso" > "$work/extract.log" 2>&1
chmod -R u+w "$work/iso"
unsquashfs -processors 2 -no-progress -d "$work/root" "$work/iso/casper/filesystem.squashfs"
python3 - "$work/root" "$overlay" <<'PY'
import json,sys
from pathlib import Path
root,overlay=map(Path,sys.argv[1:])
old=json.loads((root/'etc/seminfo/lab.json').read_text())
new=json.loads((overlay/'etc/seminfo/lab.json').read_text())
assert (old['profile'],old['lab'])==(new['profile'],new['lab']), 'ISO de outra categoria'
assert new['admission'] and len(new['admission_fingerprint'])==64
assert (root/'var/lib/seminfo-packages-ready').exists(), 'ISO SEMINFO preparada obrigatoria'
assert not any((root/'home'/name).exists() for name in ('.seminfo-lab.json','.seminfo-device.json')), 'Estado persistente nao deve ser clonado'
PY
mount -t proc proc "$work/root/proc"
mount --rbind /sys "$work/root/sys"; mount --make-rslave "$work/root/sys"
mount --rbind /dev "$work/root/dev"; mount --make-rslave "$work/root/dev"
echo 'Aplicando cliente, certificado publico fixado e configuracao da banca...'
rsync -a --chown=root:root --chmod=D755,F644 "$overlay/" "$work/root/"
# Generic host keys generated by installed packages must not be cloned to
# every participant. SSH remains disabled; no organizer private key is copied.
rm -f "$work/root/etc/ssl/private/ssl-cert-snakeoil.key" "$work/root/etc/ssl/certs/ssl-cert-snakeoil.pem"
rm -f "$work/root"/etc/ssh/ssh_host_*
python3 "$scripts/patch-casper.py" "$work/root"
install -m 755 "$scripts/99-seminfo-casper" "$work/root/usr/share/initramfs-tools/scripts/casper-bottom/99-seminfo"
hash=$(python3 "$scripts/hash-maintenance-password.py" "$passfile")
printf 'seminfo-admin:%s\n' "$hash" | chroot "$work/root" chpasswd -e
unset hash
chroot "$work/root" passwd -l root
for group in sudo admin docker; do chroot "$work/root" gpasswd -d icpc "$group" 2>/dev/null || true; done
chroot "$work/root" dconf update
chroot "$work/root" runuser -u icpc -- /usr/local/sbin/seminfo-verify --offline
version=$(find "$work/root/lib/modules" -mindepth 1 -maxdepth 1 -type d -printf '%f\n' | sort -V | tail -1)
[[ -n $version ]] || { echo 'Kernel ausente' >&2; exit 1; }
test -s "$work/root/boot/vmlinuz-$version" || cp "$work/iso/casper/vmlinuz" "$work/root/boot/vmlinuz-$version"
if [[ -s $work/root/boot/initrd.img-$version ]]; then mode=-u; else mode=-c; fi
echo 'Atualizando initramfs com as protecoes de persistencia e privilegios...'
chroot "$work/root" update-initramfs "$mode" -k "$version"
cp "$work/root/boot/vmlinuz-$version" "$work/iso/casper/vmlinuz"
cp "$work/root/boot/initrd.img-$version" "$work/iso/casper/initrd"
chroot "$work/root" dpkg-query -W --showformat='${Package} ${Version}\n' > "$work/iso/casper/filesystem.manifest"
cp "$work/iso/casper/filesystem.manifest" "${output%.iso}.packages.txt"
cleanup
echo 'Compactando o sistema atualizado (zstd, dois processadores)...'
grep -q '^CONFIG_SQUASHFS_ZSTD=y' "$work/root/boot/config-$version"
mksquashfs "$work/root" "$work/filesystem.squashfs" -noappend -comp zstd -Xcompression-level 9 -no-progress -processors 2
mv "$work/filesystem.squashfs" "$work/iso/casper/filesystem.squashfs"
du -sx --block-size=1 "$work/root" | cut -f1 > "$work/iso/casper/filesystem.size"
python3 "$scripts/patch-boot.py" "$work/iso" "$work/root/etc/seminfo/lab.json"
python3 "$scripts/generate-iso-md5.py" "$work/iso" "$source_iso" --report "$work/md5-exclusions.json"
echo 'Recriando ISO com o boot BIOS/UEFI original...'
xorriso -indev "$source_iso" -outdev "$output.partial" -boot_image any replay -update_r "$work/iso" / -commit -end > "$work/repack.log" 2>&1
mv "$output.partial" "$output"
python3 - "$work" "$expected" "${output%.iso}.build.json" "$output" <<'PY'
import hashlib,json,sys
from pathlib import Path
output=Path(sys.argv[4]);digest=hashlib.sha256()
with output.open('rb') as source:
    while data:=source.read(8*1024*1024):digest.update(data)
output.with_suffix('.iso.sha256').write_text(digest.hexdigest()+'  '+output.name+'\n')
Path(sys.argv[3]).write_text(json.dumps({'work':sys.argv[1], 'source_iso_sha256':sys.argv[2], 'offline_reconfiguration':True}))
PY
echo "ISO reconfigurada: $output"
echo "Trabalho preservado para inspecao: $work"
